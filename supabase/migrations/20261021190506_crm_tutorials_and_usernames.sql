DO $migration$
DECLARE
    profile record;
    base_name text;
    candidate text;
    suffix integer;
BEGIN
    ALTER TYPE crm.userrole ADD VALUE IF NOT EXISTS 'SISTEMAS';
    CREATE TABLE IF NOT EXISTS crm.tutorials (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title varchar(160) NOT NULL,
        description text NOT NULL DEFAULT '',
        object_path varchar(255) NOT NULL UNIQUE,
        content_type varchar(40) NOT NULL CHECK (content_type IN ('video/mp4', 'video/webm')),
        size_bytes integer NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 52428800),
        uploaded_by integer REFERENCES crm.users(id) ON DELETE SET NULL,
        created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS ix_tutorials_created_at ON crm.tutorials(created_at DESC, id DESC);
    ALTER TABLE crm.tutorials ENABLE ROW LEVEL SECURITY;
    REVOKE ALL ON TABLE crm.tutorials FROM PUBLIC, anon, authenticated;
    REVOKE ALL ON SEQUENCE crm.tutorials_id_seq FROM PUBLIC, anon, authenticated;

    -- Legacy profiles used the email as username. Preserve their login email,
    -- Auth UUID, roles and all business references, and generate unique handles.
    FOR profile IN SELECT id, username FROM crm.users WHERE position('@' IN username) > 0 ORDER BY id LOOP
        base_name := left(regexp_replace(lower(split_part(profile.username, '@', 1)), '[^a-z0-9._-]', '', 'g'), 85);
        IF length(base_name) < 3 OR base_name !~ '^[a-z0-9]' THEN
            base_name := 'usuario.' || profile.id;
        END IF;
        candidate := base_name;
        suffix := 0;
        WHILE EXISTS (SELECT 1 FROM crm.users WHERE lower(username) = candidate AND id <> profile.id) LOOP
            suffix := suffix + 1;
            candidate := base_name || '.' || profile.id || '.' || suffix;
        END LOOP;
        UPDATE crm.users SET username = candidate WHERE id = profile.id;
    END LOOP;
    CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username_lower ON crm.users(lower(username));
    INSERT INTO crm.crm_schema_migrations(version) VALUES ('supabase-tutorials-v3-ready') ON CONFLICT DO NOTHING;
END
