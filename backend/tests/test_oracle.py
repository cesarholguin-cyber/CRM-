def test_oracle_ddl_has_identity_timestamps_and_only_conditional_unique_lot_index():
    statements = []
    engine = create_mock_engine('oracle+oracledb://', lambda sql, *a, **kw: statements.append(str(sql.compile(dialect=engine.dialect))))
    Base.metadata.create_all(engine)
    sql = '\n'.join(statements)
    assert 'GENERATED BY DEFAULT AS IDENTITY' in sql
    assert 'TIMESTAMP WITH TIME ZONE' in sql
    assert 'details CLOB' in sql
    assert 'uq_sales_active_lot_oracle ON sales (CASE WHEN' in sql
    assert 'CREATE UNIQUE INDEX uq_sales_active_lot ON' not in sql
    assert "'CANCELLED', 'REVERSED'" in sql
    assert 'ON DELETE RESTRICT' not in sql
    for table in Base.metadata.sorted_tables:
        if table.name not in ('document_objects', 'intake_mutex', 'crm_schema_migrations'):
            assert table.c.id.identity is not None


