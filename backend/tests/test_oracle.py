def test_json_round_trip_oracle_unicode():
    from sqlalchemy.dialects.oracle import dialect
    kind = PortableJSON()
    payload = {'archivo': 'Titularidad José', 'ids': [1, 2]}
    assert kind.process_result_value(kind.process_bind_param(payload, dialect()), dialect()) == payload
    assert kind.process_bind_param(None, dialect()) is None


