def test_migration_preserves_ids_hashes_documents_and_refuses_occupied_target(source):
    _, engine = source
    target = create_engine('sqlite://')
    Base.metadata.create_all(target)
    with engine.connect() as original, target.begin() as destination:
        tables, counts = inspect_source(original, Base.metadata.sorted_tables)
        assert counts['sale_documents'] == 1
        copy_rows(original, destination, tables)
        assert destination.scalar(select(User.hashed_password)) == 'unchanged-hash'
        assert destination.scalar(select(Sale.client_id)) == 12
        assert destination.scalar(select(SaleDocument.content)) == b'original archived file'
        with pytest.raises(RuntimeError, match='ya contiene datos'):
            copy_rows(original, destination, tables)
        destination.execute(Sale.__table__.update().values(sale_price=1))
        with pytest.raises(RuntimeError, match='sales'):
            verify_rows(original, destination, tables)
    target.dispose()


def test_backup_never_overwrites_and_readonly_source_rejects_writes(source, tmp_path):
    path, engine = source
    backup = tmp_path / 'backup.db'
    backup_source(path, backup)
    assert backup.stat().st_mode & 0o777 == 0o600
    with pytest.raises(FileExistsError):
        backup_source(path, backup)
    readonly = source_engine(backup)
    with readonly.connect() as connection:
        assert connection.scalar(select(User.id)) == 7
        with pytest.raises(Exception, match='readonly'):
            connection.execute(text('DELETE FROM users'))
    readonly.dispose()


