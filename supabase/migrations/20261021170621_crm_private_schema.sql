BEGIN;

CREATE SCHEMA IF NOT EXISTS crm;

SET LOCAL search_path TO crm;

REVOKE ALL ON SCHEMA crm FROM PUBLIC, anon, authenticated;

CREATE TYPE userrole AS ENUM ('ADMIN', 'PROMOTOR');

CREATE TYPE projectstatus AS ENUM ('ACTIVE', 'COMPLETED', 'PAUSED', 'CANCELLED');

CREATE TYPE lotstatus AS ENUM ('AVAILABLE', 'RESERVED', 'SOLD', 'BLOCKED');

CREATE TYPE clientstatus AS ENUM ('LEAD', 'CONTACTED', 'VISIT_SCHEDULED', 'VISIT_COMPLETED', 'INTERESTED', 'RESERVATION', 'SOLD', 'LOST');

CREATE TYPE leadsource AS ENUM ('WEBSITE', 'WHATSAPP', 'FACEBOOK', 'INSTAGRAM', 'REFERRAL', 'PHONE', 'VISIT', 'OTHER');

CREATE TYPE salestatus AS ENUM ('RESERVED', 'OPTION_SIGNED', 'CONTRACT_SIGNED', 'FINANCING', 'PAID', 'CANCELLED', 'REVERSED');

CREATE TABLE users (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	email VARCHAR(255) NOT NULL,
	username VARCHAR(100) NOT NULL,
	hashed_password VARCHAR(255) NOT NULL,
	full_name VARCHAR(255) NOT NULL,
	phone VARCHAR(50),
	role userrole NOT NULL,
	is_active BOOLEAN,
	is_superuser BOOLEAN,
	totp_secret VARCHAR(64),
	totp_enabled BOOLEAN,
	failed_login_attempts INTEGER,
	locked_until TIMESTAMP WITH TIME ZONE,
	last_login TIMESTAMP WITH TIME ZONE,
	password_changed_at TIMESTAMP WITH TIME ZONE,
	must_change_password BOOLEAN,
	created_at TIMESTAMP WITH TIME ZONE,
	updated_at TIMESTAMP WITH TIME ZONE,
	PRIMARY KEY (id)
);

CREATE UNIQUE INDEX ix_users_email ON users (email);

CREATE UNIQUE INDEX ix_users_username ON users (username);

CREATE TABLE projects (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(255) NOT NULL,
	slug VARCHAR(255) NOT NULL,
	description TEXT,
	location VARCHAR(500),
	city VARCHAR(255),
	state VARCHAR(255),
	country VARCHAR(100),
	price_per_sqm FLOAT NOT NULL,
	total_lots INTEGER NOT NULL,
	available_lots INTEGER NOT NULL,
	sold_lots INTEGER NOT NULL,
	status projectstatus,
	cover_image_url VARCHAR(500),
	gallery VARCHAR(2000),
	created_at TIMESTAMP WITH TIME ZONE,
	updated_at TIMESTAMP WITH TIME ZONE,
	PRIMARY KEY (id),
	UNIQUE (slug)
);

CREATE TABLE intake_mutex (
	id INTEGER NOT NULL,
	PRIMARY KEY (id)
);

CREATE TABLE crm_schema_migrations (
	version VARCHAR(80) NOT NULL,
	PRIMARY KEY (version)
);

CREATE TABLE audit_logs (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
	user_id INTEGER,
	username VARCHAR(100),
	action VARCHAR(50) NOT NULL,
	entity_type VARCHAR(50) NOT NULL,
	entity_id INTEGER,
	ip_address VARCHAR(45),
	user_agent VARCHAR(500),
	details JSON,
	old_values JSON,
	new_values JSON,
	PRIMARY KEY (id)
);

CREATE INDEX ix_audit_logs_timestamp ON audit_logs (timestamp);

CREATE INDEX ix_audit_logs_action ON audit_logs (action);

CREATE TABLE clients (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	project_id INTEGER,
	full_name VARCHAR(500) NOT NULL,
	email VARCHAR(500),
	phone VARCHAR(500),
	address VARCHAR(1000),
	status clientstatus NOT NULL,
	lead_source leadsource,
	notes TEXT,
	budget_range VARCHAR(255),
	preferred_lot_size FLOAT,
	assigned_agent_id INTEGER,
	created_at TIMESTAMP WITH TIME ZONE,
	updated_at TIMESTAMP WITH TIME ZONE,
	PRIMARY KEY (id),
	FOREIGN KEY(project_id) REFERENCES projects (id),
	FOREIGN KEY(assigned_agent_id) REFERENCES users (id)
);

CREATE INDEX ix_clients_status ON clients (status);

CREATE INDEX ix_clients_assigned_agent_id ON clients (assigned_agent_id);

CREATE INDEX ix_clients_project_id ON clients (project_id);

CREATE TABLE lots (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	project_id INTEGER NOT NULL,
	lot_number INTEGER NOT NULL,
	block VARCHAR(50),
	area_sqm FLOAT NOT NULL,
	price_per_sqm FLOAT NOT NULL,
	total_price FLOAT NOT NULL,
	status lotstatus NOT NULL,
	map_coordinates VARCHAR(500),
	sold_to_client_id INTEGER,
	sold_at TIMESTAMP WITH TIME ZONE,
	created_at TIMESTAMP WITH TIME ZONE,
	updated_at TIMESTAMP WITH TIME ZONE,
	PRIMARY KEY (id),
	FOREIGN KEY(project_id) REFERENCES projects (id),
	FOREIGN KEY(sold_to_client_id) REFERENCES clients (id)
);

CREATE INDEX ix_lots_status ON lots (status);

CREATE INDEX ix_lots_project_id ON lots (project_id);

CREATE TABLE client_interactions (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	client_id INTEGER NOT NULL,
	user_id INTEGER,
	interaction_type VARCHAR(50) NOT NULL,
	notes TEXT,
	channel VARCHAR(50),
	metadata_json VARCHAR(2000),
	created_at TIMESTAMP WITH TIME ZONE,
	PRIMARY KEY (id),
	FOREIGN KEY(client_id) REFERENCES clients (id),
	FOREIGN KEY(user_id) REFERENCES users (id)
);

CREATE INDEX ix_client_interactions_client_id ON client_interactions (client_id);

CREATE TABLE sales (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	client_id INTEGER NOT NULL,
	lot_id INTEGER NOT NULL,
	agent_id INTEGER,
	sale_price FLOAT NOT NULL,
	down_payment FLOAT NOT NULL,
	financing_amount FLOAT NOT NULL,
	interest_rate FLOAT,
	payment_terms_months INTEGER,
	monthly_payment FLOAT,
	status salestatus NOT NULL,
	notes TEXT,
	reservation_expires_at TIMESTAMP WITH TIME ZONE,
	commission_percentage FLOAT,
	commission_amount FLOAT,
	created_at TIMESTAMP WITH TIME ZONE,
	updated_at TIMESTAMP WITH TIME ZONE,
	closed_at TIMESTAMP WITH TIME ZONE,
	PRIMARY KEY (id),
	FOREIGN KEY(client_id) REFERENCES clients (id),
	FOREIGN KEY(lot_id) REFERENCES lots (id),
	FOREIGN KEY(agent_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX uq_sales_active_lot ON sales (lot_id) WHERE status NOT IN ('CANCELLED', 'REVERSED');

CREATE INDEX ix_sales_client_id ON sales (client_id);

CREATE INDEX ix_sales_lot_id ON sales (lot_id);

CREATE TABLE payment_plans (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	sale_id INTEGER NOT NULL,
	client_id INTEGER NOT NULL,
	installment_number INTEGER NOT NULL,
	due_date TIMESTAMP WITH TIME ZONE NOT NULL,
	amount FLOAT NOT NULL,
	paid_amount FLOAT,
	is_paid BOOLEAN,
	paid_at TIMESTAMP WITH TIME ZONE,
	late_fee FLOAT,
	notes VARCHAR(500),
	created_at TIMESTAMP WITH TIME ZONE,
	PRIMARY KEY (id),
	FOREIGN KEY(sale_id) REFERENCES sales (id),
	FOREIGN KEY(client_id) REFERENCES clients (id)
);

CREATE INDEX ix_payment_plans_client_id ON payment_plans (client_id);

CREATE INDEX ix_payment_plans_sale_id ON payment_plans (sale_id);

CREATE TABLE sale_documents (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	sale_id INTEGER NOT NULL,
	category VARCHAR(40) NOT NULL,
	filename VARCHAR(255) NOT NULL,
	content_type VARCHAR(120) NOT NULL,
	size_bytes INTEGER NOT NULL,
	sha256 VARCHAR(64) NOT NULL,
	description TEXT,
	uploaded_by INTEGER NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE NOT NULL,
	content BYTEA NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY(sale_id) REFERENCES sales (id),
	FOREIGN KEY(uploaded_by) REFERENCES users (id)
);

CREATE INDEX ix_sale_documents_sale_id ON sale_documents (sale_id);

CREATE TABLE payments (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	sale_id INTEGER NOT NULL,
	payment_plan_id INTEGER,
	amount FLOAT NOT NULL,
	payment_method VARCHAR(50),
	reference_number VARCHAR(255),
	receipt_url VARCHAR(500),
	notes VARCHAR(500),
	paid_by VARCHAR(255),
	created_at TIMESTAMP WITH TIME ZONE,
	PRIMARY KEY (id),
	FOREIGN KEY(sale_id) REFERENCES sales (id),
	FOREIGN KEY(payment_plan_id) REFERENCES payment_plans (id)
);

CREATE INDEX ix_payments_sale_id ON payments (sale_id);

CREATE TABLE document_objects (
	document_id INTEGER NOT NULL,
	namespace VARCHAR(255) NOT NULL,
	bucket VARCHAR(255) NOT NULL,
	object_key VARCHAR(500) NOT NULL,
	PRIMARY KEY (document_id),
	FOREIGN KEY(document_id) REFERENCES sale_documents (id),
	UNIQUE (object_key)
);

ALTER TABLE crm."audit_logs" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."crm_schema_migrations" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."intake_mutex" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."projects" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."users" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."clients" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."client_interactions" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."lots" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."sales" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."payment_plans" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."sale_documents" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."document_objects" ENABLE ROW LEVEL SECURITY;

ALTER TABLE crm."payments" ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA crm FROM PUBLIC, anon, authenticated;

REVOKE ALL ON ALL SEQUENCES IN SCHEMA crm FROM PUBLIC, anon, authenticated;

ALTER DEFAULT PRIVILEGES IN SCHEMA crm REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;

COMMIT;
