def test_oci_download_checks_private_access_size_and_hash():
    from io import BytesIO
    payload = b'original'
    class Stream:
        def stream(self, *args, **kwargs):
            yield payload
    data = SimpleNamespace(raw=Stream(), close=lambda: None)
    client = SimpleNamespace(get_bucket=lambda *a: SimpleNamespace(data=SimpleNamespace(public_access_type='NoPublicAccess')),
                             get_object=lambda *a: SimpleNamespace(data=data))
    storage = OracleObjectStorage.__new__(OracleObjectStorage)
    storage.client = client
    assert storage.get('ns', 'bucket', 'key', len(payload), sha256(payload).hexdigest()) == payload
    with pytest.raises(StorageError):
        storage.get('ns', 'bucket', 'key', 1, sha256(payload).hexdigest())
    with pytest.raises(StorageError):
        storage.get('ns', 'bucket', 'key', len(payload), 'bad hash')
    client.get_bucket = lambda *a: SimpleNamespace(data=SimpleNamespace(public_access_type='ObjectRead'))
    with pytest.raises(StorageError, match='privado'):
        storage.get('ns', 'bucket', 'key', len(payload), sha256(payload).hexdigest())
